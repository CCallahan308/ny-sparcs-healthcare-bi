"""Central configuration: deterministic paths, logging, and shared constants.

All paths derive from PROJECT_ROOT so the pipeline runs from any working
directory with no hardcoded local absolute paths. Raw and working files can
be redirected outside the repository via the SPARCS_BI_DATA_ROOT environment
variable (useful where the repository sits in a cloud-synced folder); marts
always stay inside the repository because they are small and selectively
committed.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Static source registry, generated by scripts/inspect_sources.py.
SOURCE_REGISTRY = PROJECT_ROOT / "src" / "sources.toml"

DATA_ROOT = Path(os.environ.get("SPARCS_BI_DATA_ROOT", str(PROJECT_ROOT / "data")))

DATA_DIR = DATA_ROOT
RAW_DIR = DATA_ROOT / "raw"
PROCESSED_DIR = DATA_ROOT / "processed"
DUCKDB_PATH = PROCESSED_DIR / "sparcs.duckdb"

# Marts are committable artifacts and stay anchored to the repository.
MARTS_DIR = PROJECT_ROOT / "data" / "marts"

HISTORY_START_YEAR = 2009
